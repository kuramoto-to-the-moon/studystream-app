export function translateInterfaceText(language: InterfaceLanguage, source: string) {
  return language === 'en' ? (englishInterfaceCopy[source] ?? source) : source;
}

type I18nValue = {
  language: InterfaceLanguage;
  setLanguage: (language: InterfaceLanguage) => void;
  t: (source: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function getPreferredInterfaceLanguage(): InterfaceLanguage {
  if (typeof window === 'undefined') return 'ja';
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === 'ja' || saved === 'en') return saved;
  return window.navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<InterfaceLanguage>(getPreferredInterfaceLanguage);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (source) => translateInterfaceText(language, source),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
